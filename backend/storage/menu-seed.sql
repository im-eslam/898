DECLARE
  n integer;
BEGIN
  SELECT count(*) INTO n FROM menu_settings;
  IF n <> 1 THEN RAISE EXCEPTION 'menu_settings: expected 1, got %', n; END IF;

  SELECT count(*) INTO n FROM menu_categories;
  IF n <> 12 THEN RAISE EXCEPTION 'menu_categories: expected 12, got %', n; END IF;

  SELECT count(*) INTO n FROM menu_add_ons;
  IF n <> 5 THEN RAISE EXCEPTION 'menu_add_ons: expected 5, got %', n; END IF;

  SELECT count(*) INTO n FROM menu_products;
  IF n <> 82 THEN RAISE EXCEPTION 'menu_products: expected 82, got %', n; END IF;

  SELECT count(*) INTO n FROM menu_product_options;
  IF n <> 82 THEN RAISE EXCEPTION 'menu_product_options: expected 82, got %', n; END IF;

  SELECT count(*) INTO n FROM menu_product_add_ons;
  IF n <> 152 THEN RAISE EXCEPTION 'menu_product_add_ons: expected 152, got %', n; END IF;

  SELECT count(*) INTO n FROM menu_product_barista_way;
  IF n <> 0 THEN RAISE EXCEPTION 'menu_product_barista_way: expected 0, got %', n; END IF;

  SELECT count(*) INTO n FROM menu_product_related;
  IF n <> 246 THEN RAISE EXCEPTION 'menu_product_related: expected 246, got %', n; END IF;

  SELECT count(*) INTO n FROM menu_product_related WHERE related_product_id = product_id;
  IF n <> 0 THEN RAISE EXCEPTION 'menu_product_related: % self-references found', n; END IF;

  SELECT count(*) INTO n FROM (
    SELECT product_id FROM menu_product_related GROUP BY product_id HAVING count(*) <> 3
  ) x;
  IF n <> 0 THEN RAISE EXCEPTION 'menu_product_related: % products do not have exactly 3 suggestions', n; END IF;

  SELECT count(*) INTO n FROM menu_signatures;
  IF n <> 5 THEN RAISE EXCEPTION 'menu_signatures: expected 5, got %', n; END IF;

  SELECT count(*) INTO n FROM menu_pairings;
  IF n <> 0 THEN RAISE EXCEPTION 'menu_pairings: expected 0, got %', n; END IF;

  SELECT count(*) INTO n FROM menu_pairing_items;
  IF n <> 0 THEN RAISE EXCEPTION 'menu_pairing_items: expected 0, got %', n; END IF;

  RAISE NOTICE 'Menu seed verified: 1 settings, 12 categories, 82 products, 82 options, 5 add-ons, 152 product add-on links, 246 related links, 5 signatures.';
END $$;

